$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("# Public API for Later Tasks (generated by tools/generate-m0-api.ps1)")
[void]$sb.AppendLine()
[void]$sb.AppendLine("All signatures below are taken from the compiled bytecode by javap; do not hand-edit.")

foreach ($cls in $classes) {
    $rel = $cls -replace '\.', '/'
    $classFile = Join-Path $ClassesRoot "$rel.class"
    if (-not (Test-Path $classFile)) {
        Write-Warning "Missing class file: $classFile"
        continue
    }
    $simple = $cls.Substring($cls.LastIndexOf('.') + 1)
    $pkg = $cls.Substring(0, $cls.LastIndexOf('.'))
    [void]$sb.AppendLine("### $simple ($pkg)")
    [void]$sb.AppendLine('```java')
    $lines = javap -p $classFile 2>&1
    foreach ($rawLine in $lines) {
        $line = $rawLine.ToString().Trim()
        if ($line -eq "") { continue }
        if ($line.StartsWith("Compiled from")) { continue }
        if ($line -match '^public final class .* extends .*Record') { continue } # record header, still print? skip header
        if ($line -match '^public (final )?class |^interface |^public interface |^enum ') { continue }
        if ($line -match 'private') { continue }
        if ($line -notmatch '\(') { continue } # fields are not method/constructor signatures
        # drop obvious Object methods
        if ($line -match '^(public )?(final )?(int )?hashCode\(\)' ) { continue }
        if ($line -match '^public boolean equals\(java\.lang\.Object\)' ) { continue }
        if ($line -match 'toString\(\)$' -and $line -notmatch 'layerTicks') { } else { }
        if ($line.EndsWith(";")) { [void]$sb.AppendLine($line) } else { [void]$sb.AppendLine($line + ";") }
    }
    [void]$sb.AppendLine('```')
    [void]$sb.AppendLine()
}

[System.IO.File]::WriteAllText($Output, $sb.ToString())
Write-Host "Wrote $Output"