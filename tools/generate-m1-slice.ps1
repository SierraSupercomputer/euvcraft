[void]$sb.AppendLine("| Coordinator owns Git commits, integration, verification | Decided | AGENTS.md |")
[void]$sb.AppendLine("| Workers edit only task scope in isolated worktrees | Decided | AGENTS.md |")
[void]$sb.AppendLine("| No resolved questions left open; no guessed decisions | Decided | BRIEF.txt |")
[void]$sb.AppendLine()

# --- 26.3 API Notes ---
[void]$sb.AppendLine("## 26.3 API Notes (actual report source references)")
[void]$sb.AppendLine()
[void]$sb.AppendLine("| Note | Source |")
[void]$sb.AppendLine("|------|--------|")
[void]$sb.AppendLine("| Verified runtime reload pack metadata: `{"pack":{"description":"EUVCRAFT M1 recipe override test","min_format":121,"max_format":[121,0]}}` | Minecraft 26.3 codec output |")
[void]$sb.AppendLine("| M1ReloadGameTests: full 400 paid ticks 20->27->20 FE, restore original pack selection | Actual test source |")
[void]$sb.AppendLine("| GameTestFixtures: explicit JVM `lithmodFixtures` flag AND nonproduction gate; normal client/server false | BRIEF.txt verified source behavior |")
[void]$sb.AppendLine("| Probe mode: `-PlithmodFixtures=false -PlithmodShippingProbe=true` registers one off-mode case | BRIEF.txt |")
[void]$sb.AppendLine("| Release jar: exact 8 fixture JSON excluded; processResources/testOutput keep fixtures | BRIEF.txt |")
[void]$sb.AppendLine("| Both pickaxe and needs_stone_tool tag test_machine entries optional; production 7 blocks unchanged | BRIEF.txt |")
[void]$sb.AppendLine("| data/lithmod/tags/block/machine.json also optional test_machine reference | Fixture repair verified |")
[void]$sb.AppendLine("| Fixture loot table uses neoforge:conditions registered minecraft:item lithmod:test_machine | NeoForge 26.3.0.69-beta source-confirmed |")
[void]$sb.AppendLine("| Baseline original M0 compiled-signature output captured in build/M1-12-original-m0-api.md SHA256 b2807c9d1925705fdfc499ca1f9b7d1b65422a5ca104697ab5f46df38d7f25f6 | BRIEF.txt |")
[void]$sb.AppendLine()

# Write output
$outputContent = $sb.ToString()

if ($Check) {
    if (-not (Test-Path $Output)) {
        Write-Error "Check failed: $Output does not exist"
        exit 1
    }
    $existing = Read-FileUtf8 $Output
    if ($existing -ne $outputContent) {
        Write-Error "Check failed: $Output is stale (content mismatch)"
        exit 1
    }
    Write-Host "Check passed: $Output is up to date"
} else {
    Write-FileUtf8 $Output $outputContent
    Write-Host "Wrote $Output"
}