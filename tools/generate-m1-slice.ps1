[void]$sb.AppendLine("| Machine Recipe | `data/lithmod/machine_recipes/<name>.json` |")
[void]$sb.AppendLine("| Tier | `data/lithmod/tiers/t<index>.json` |")
[void]$sb.AppendLine("| Die Rules | `data/lithmod/die_rules/<name>.json` |")
[void]$sb.AppendLine("| Support Lines | `data/lithmod/support_lines/<name>.json` |")
[void]$sb.AppendLine("| Fixture (test-only) | `test/resources/data/lithmod/**/*.json` |")
[void]$sb.AppendLine()

# --- Open/Decided Design Decisions ---
[void]$sb.AppendLine("## Open/Decided Design Decisions (per docs/reports precedence)")
[void]$sb.AppendLine()
[void]$sb.AppendLine("| Decision | Status | Source Reference |")
[void]$sb.AppendLine("|----------|--------|------------------|")
[void]$sb.AppendLine("| M1 source precedence over older references | Decided | User-confirmed in EUVCRAFT_TAKEOVER.md |")
[void]$sb.AppendLine("| T6 core-count decision (6 cores, optional tier) | Decided | User-confirmed, overrides older refs |")
[void]$sb.AppendLine("| M1 pack scope: Nemotron writes code/docs, Beam reviews | Decided | User-authorized after consolidation |")
