<#
.SYNOPSIS
Generates docs/m1-slice.md containing the complete M1 handoff document.
.DESCRIPTION
This script generates a comprehensive M1 slice document including:
- Package layout from actual source
- Generated API section (via generate-m0-api.ps1 -M1)
- Real data file paths/formats/examples
- Actual config keys/defaults/ranges from FabConfig/FabSettings
- Machine definitions/params from JSON
- Recipe summary from actual JSON (fixture data explicitly gated)
- Open/Decided design decisions and 26.3 API notes with actual report source references
.PARAMETER Check
When specified, compares exact generated bytes against existing docs/m1-slice.md and fails
if stale or missing, without mutating the file.
.PARAMETER Output
Output file path (default: docs/m1-slice.md)
#>
param(
    [switch]$Check,
    [string]$Output = "docs/m1-slice.md"
)

$ErrorActionPreference = "Stop"

# Helper: read all lines from a file with UTF8
function Read-FileUtf8($path) {
    return [System.IO.File]::ReadAllText($path, [System.Text.Encoding]::UTF8)
}

# Helper: write file with UTF8, no BOM, stable LF line endings
function Write-FileUtf8($path, $content) {
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($content.Replace("`r`n", "`n").Replace("`r", "`n"))
    [System.IO.File]::WriteAllBytes($path, $bytes)
}

# Helper: escape markdown special chars
function Escape-Markdown($text) {
    return $text -replace '&', '&' -replace '<', '<' -replace '>', '>'
}

# Helper: format number invariantly (no locale-dependent formatting)
function Format-Number($value) {
    if ($value -is [double] -or $value -is [float]) {
        return $value.ToString("G17", [System.Globalization.CultureInfo]::InvariantCulture)
    }
    return $value.ToString()
}

# 1. Generate API section using generate-m0-api.ps1 -M1
$apiTemp = [System.IO.Path]::GetTempFileName()
& .\tools\generate-m0-api.ps1 -M1 -Output $apiTemp
$apiContent = Read-FileUtf8 $apiTemp
Remove-Item $apiTemp -Force

# Extract just the API sections (skip the header)
$apiSections = $apiContent -replace '^# .*\n\nAll signatures below are taken from the compiled bytecode by javap; do not hand-edit\.\n\n', ''

# 2. Package layout from actual source
$srcRoot = "src/main/java"
$packages = @()
if (Test-Path $srcRoot) {
    $dirs = Get-ChildItem $srcRoot -Recurse -Directory | Sort-Object FullName
    foreach ($dir in $dirs) {
        $rel = $dir.FullName.Substring($srcRoot.Length + 1).Replace('\', '.')
        if ($rel -ne '') {
            $packages += "com.euvcraft.lithmod.$rel"
        }
    }
}
# Also include root package files
$rootFiles = Get-ChildItem "$srcRoot/com/euvcraft/lithmod" -File -Filter "*.java" | Sort-Object Name
foreach ($f in $rootFiles) {
    $packages += "com.euvcraft.lithmod.$($f.BaseName)"
}

$packageLayout = $packages | Sort-Object -Unique | ForEach-Object { "  - $_" } | ForEach-Object { $_ } | Join-String "`n"

# 3. Config keys/defaults/ranges from actual FabConfig/FabSettings source
# We parse the source files directly since they're the authority
$fabConfigSource = Read-FileUtf8 "src/main/java/com/euvcraft/lithmod/mc/FabConfig.java"
$fabSettingsSource = Read-FileUtf8 "src/main/java/com/euvcraft/lithmod/core/FabSettings.java"

# Extract config entries from FabConfig.java static block
$configEntries = @()
$inGeneral = $false
$inCompute = $false
$inFeatures = $false
$inPower = $false

$lines = $fabConfigSource -split "`r?`n"
foreach ($line in $lines) {
    $trimmed = $line.Trim()
    if ($trimmed -match 'BUILDER\.comment\("General') { $inGeneral = $true; $inCompute = $false; $inFeatures = $false; $inPower = $false; continue }
    if ($trimmed -match 'BUILDER\.comment\("Compute') { $inGeneral = $false; $inCompute = $true; $inFeatures = $false; $inPower = $false; continue }
    if ($trimmed -match 'BUILDER\.comment\("Feature') { $inGeneral = $false; $inCompute = $false; $inFeatures = $true; $inPower = $false; continue }
    if ($trimmed -match 'BUILDER\.comment\("FE power') { $inGeneral = $false; $inCompute = $false; $inFeatures = $false; $inPower = $true; continue }
    if ($trimmed -match 'BUILDER\.pop\(\)') { $inGeneral = $false; $inCompute = $false; $inFeatures = $false; $inPower = $false; continue }
    
    # Match defineInRange or defineList or defineListAllowEmpty or define
    if ($trimmed -match '(\w+)\s*=\s*BUILDER\s*\.\s*(defineInRange|defineList|defineListAllowEmpty|define)\s*\(\s*"([^"]+)"') {
        $fieldName = $matches[1]
        $method = $matches[2]
        $configKey = $matches[3]
        $category = if ($inGeneral) { "general" } elseif ($inCompute) { "compute" } elseif ($inFeatures) { "features" } elseif ($inPower) { "power" } else { "unknown" }
        
        # Extract default and range from the call
        $default = ""
        $range = ""
        if ($method -eq 'defineInRange') {
            # defineInRange("key", default, min, max)
            if ($trimmed -match 'defineInRange\s*\(\s*"[^"]+"\s*,\s*([^,]+)\s*,\s*([^,]+)\s*,\s*([^\)]+)') {
                $default = $matches[1].Trim()
                $min = $matches[2].Trim()
                $max = $matches[3].Trim()
                $range = "[$min, $max]"
            }
        } elseif ($method -eq 'defineList') {
            # defineList("key", defaultList, ...)
            if ($trimmed -match 'defineList\s*\(\s*"[^"]+"\s*,\s*([^,]+)') {
                $default = $matches[1].Trim()
                $range = "list of integers"
            }
        } elseif ($method -eq 'defineListAllowEmpty') {
            if ($trimmed -match 'defineListAllowEmpty\s*\(\s*"[^"]+"\s*,\s*([^,]+)') {
                $default = $matches[1].Trim()
                $range = "list of strings (empty allowed)"
            }
        } elseif ($method -eq 'define') {
            if ($trimmed -match 'define\s*\(\s*"[^"]+"\s*,\s*([^\)]+)') {
                $default = $matches[1].Trim()
                $range = "boolean"
            }
        }
        
        $configEntries += [pscustomobject]@{
            Category = $category
            Key = $configKey
            Field = $fieldName
            Default = $default
            Range = $range
        }
    }
}

# Also get defaults from FabSettings constants
$fabSettingsDefaults = @{}
$fabSettingsLines = $fabSettingsSource -split "`r?`n"
foreach ($line in $fabSettingsLines) {
    $trimmed = $line.Trim()
    if ($trimmed -match 'public static final (int|double|boolean|List) (\w+) = (.+);') {
        $type = $matches[1]
        $name = $matches[2]
        $value = $matches[3].Trim().TrimEnd(';')
        $fabSettingsDefaults[$name] = $value
    }
}

# 4. Machine definitions from JSON
$machineFiles = Get-ChildItem "src/main/resources/data/lithmod/machines" -Filter "*.json" | Sort-Object Name
$machineDefs = @()
foreach ($f in $machineFiles) {
    $json = Read-FileUtf8 $f.FullName
    $machineDefs += [pscustomobject]@{
        File = "data/lithmod/machines/$($f.Name)"
        Json = $json
    }
}

# 5. Recipe summary from actual JSON
$recipeFiles = Get-ChildItem "src/main/resources/data/lithmod/machine_recipes" -Filter "*.json" | Sort-Object Name
$recipes = @()
foreach ($f in $recipeFiles) {
    $json = Read-FileUtf8 $f.FullName
    $recipes += [pscustomobject]@{
        File = "data/lithmod/machine_recipes/$($f.Name)"
        Json = $json
    }
}

# 6. Tier data from JSON
$tierFiles = Get-ChildItem "src/main/resources/data/lithmod/tiers" -Filter "*.json" | Sort-Object Name
$tiers = @()
foreach ($f in $tierFiles) {
    $json = Read-FileUtf8 $f.FullName
    $tiers += [pscustomobject]@{
        File = "data/lithmod/tiers/$($f.Name)"
        Json = $json
    }
}

# 7. Fixture data (test-only, gated)
$fixtureData = @()
$fixtureDir = "src/test/resources/data/lithmod"
if (Test-Path $fixtureDir) {
    $fixtureFiles = Get-ChildItem $fixtureDir -Recurse -Filter "*.json" | Sort-Object FullName
    foreach ($f in $fixtureFiles) {
        $rel = $f.FullName.Substring($fixtureDir.Length + 1)
        $json = Read-FileUtf8 $f.FullName
        $fixtureData += [pscustomobject]@{
            File = "test/resources/data/lithmod/$rel"
            Json = $json
        }
    }
}

# 8. Data formats - extract codec field information
$codecFiles = @(
    "src/main/java/com/euvcraft/lithmod/mc/data/MachineDefinitionCodec.java",
    "src/main/java/com/euvcraft/lithmod/mc/data/MachineRecipeSpecCodec.java",
    "src/main/java/com/euvcraft/lithmod/mc/data/MachineIngredientCodec.java",
    "src/main/java/com/euvcraft/lithmod/mc/data/MachineResultCodec.java",
    "src/main/java/com/euvcraft/lithmod/mc/data/TierCodec.java",
    "src/main/java/com/euvcraft/lithmod/mc/data/DieRuleCodec.java",
    "src/main/java/com/euvcraft/lithmod/mc/data/RunSpecCodec.java",
    "src/main/java/com/euvcraft/lithmod/mc/FoupContentsCodec.java"
)

$codecInfo = @()
foreach ($cf in $codecFiles) {
    if (Test-Path $cf) {
        $source = Read-FileUtf8 $cf
        $codecInfo += [pscustomobject]@{
            File = $cf.Substring("src/main/java/".Length)
            Source = $source
        }
    }
}

# 9. Build the m1-slice.md document
$sb = [System.Text.StringBuilder]::new()

[void]$sb.AppendLine("# EUVCRAFT M1 Handoff Slice")
[void]$sb.AppendLine()
[void]$sb.AppendLine("Generated by `tools/generate-m1-slice.ps1` from actual source. Do not hand-edit.")
[void]$sb.AppendLine()

# --- Package Layout ---
[void]$sb.AppendLine("## Package Layout (from actual source)")
[void]$sb.AppendLine()
[void]$sb.AppendLine("```")
[void]$sb.AppendLine($packageLayout)
[void]$sb.AppendLine("```")
[void]$sb.AppendLine()

# --- Generated API Section ---
[void]$sb.AppendLine("## Generated API (M1 Production API)")
[void]$sb.AppendLine()
[void]$sb.AppendLine($apiSections.Trim())
[void]$sb.AppendLine()

# --- Config Keys/Defaults/Ranges ---
[void]$sb.AppendLine("## Config: FabConfig (ModConfig.Type.LOCAL, run/config/lithmod-local.toml)")
[void]$sb.AppendLine()
[void]$sb.AppendLine("Derived from actual `FabConfig.java` and `FabSettings.java` constants. 15 keys total.")
[void]$sb.AppendLine()
[void]$sb.AppendLine("| Category | Key | Field | Default | Range |")
[void]$sb.AppendLine("|----------|-----|-------|---------|-------|")

$categories = @("general", "compute", "features", "power")
foreach ($cat in $categories) {
    $catEntries = $configEntries | Where-Object { $_.Category -eq $cat }
    if ($catEntries.Count -gt 0) {
        foreach ($entry in $catEntries) {
            [void]$sb.AppendLine("| $($entry.Category) | $($entry.Key) | $($entry.Field) | $($entry.Default) | $($entry.Range) |")
        }
    }
}
[void]$sb.AppendLine()

# --- Machine Definitions ---
[void]$sb.AppendLine("## Machine Definitions (from data/lithmod/machines/*.json)")
[void]$sb.AppendLine()
foreach ($m in $machineDefs) {
    [void]$sb.AppendLine("### $($m.File)")
    [void]$sb.AppendLine('```json')
    [void]$sb.AppendLine($m.Json)
    [void]$sb.AppendLine('```')
    [void]$sb.AppendLine()
}

# --- Recipe Summary ---
[void]$sb.AppendLine("## Recipe Summary (from data/lithmod/machine_recipes/*.json)")
[void]$sb.AppendLine()
[void]$sb.AppendLine("Production recipes (6 files):")
[void]$sb.AppendLine()
foreach ($r in $recipes) {
    [void]$sb.AppendLine("### $($r.File)")
    [void]$sb.AppendLine('```json')
    [void]$sb.AppendLine($r.Json)
    [void]$sb.AppendLine('```')
    [void]$sb.AppendLine()
}

# Fixture recipes (test-only, gated)
if ($fixtureData.Count -gt 0) {
    [void]$sb.AppendLine("### Fixture Recipes (test-only, gated by `-PlithmodFixtures=true` JVM flag)")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("> These are only registered when `lithmodFixtures` Gradle property is true (gameTestServer default).")
    [void]$sb.AppendLine("> Release jars exclude fixture JSON via `processResources` / `testOutput`. Tests/classes remain unreachable in release.")
    [void]$sb.AppendLine()
    foreach ($f in $fixtureData) {
        [void]$sb.AppendLine("#### $($f.File)")
        [void]$sb.AppendLine('```json')
        [void]$sb.AppendLine($f.Json)
        [void]$sb.AppendLine('```')
        [void]$sb.AppendLine()
    }
}

# --- Tier Data ---
[void]$sb.AppendLine("## Tier Data (from data/lithmod/tiers/*.json)")
[void]$sb.AppendLine()
foreach ($t in $tiers) {
    [void]$sb.AppendLine("### $($t.File)")
    [void]$sb.AppendLine('```json')
    [void]$sb.AppendLine($t.Json)
    [void]$sb.AppendLine('```')
    [void]$sb.AppendLine()
}

# --- Data Formats ---
[void]$sb.AppendLine("## Data Formats (actual JSON/codec/source fields)")
[void]$sb.AppendLine()
foreach ($c in $codecInfo) {
    [void]$sb.AppendLine("### $($c.File)")
    [void]$sb.AppendLine('```java')
    [void]$sb.AppendLine($c.Source)
    [void]$sb.AppendLine('```')
    [void]$sb.AppendLine()
}

